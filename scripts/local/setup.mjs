export async function startInfra() {
  heading("Starting Postgres, Redis, and ClickHouse");
  info("docker compose -f docker-compose.local.yml up -d --wait");
  try {
    await run("docker", ["compose", "-f", "docker-compose.local.yml", "up", "-d", "--wait", "--wait-timeout", "120"], {
      cwd: ROOT,
    });
  } catch (err) {
    fail("One or more containers didn't become healthy in time.");
    console.log(`\n  ${err.message}`);
    console.log("\n  Check what's wrong with:");
    console.log("    docker compose -f docker-compose.local.yml ps");
    console.log("    docker compose -f docker-compose.local.yml logs\n");
    process.exit(1);
  }
  ok("Postgres, Redis, and ClickHouse are healthy");
}

export async function installDependencies() {
  if (existsSync(P("node_modules")) && existsSync(P("apps/api/node_modules"))) {
    ok("Dependencies already installed");
    return;
  }
  heading("Installing dependencies (first run only — this takes a minute or two)");
  // Puppeteer's Chromium download is the #1 way a fresh install hangs or fails on a flaky/
  // restricted network — apps/api/.puppeteerrc.cjs skips it by default already, but setting this
  // here too means it's skipped even the very first time, before that config file's package has
  // been resolved.
  await run("pnpm", ["install"], { cwd: ROOT, env: { ...process.env, PUPPETEER_SKIP_DOWNLOAD: "true" } });
  ok("Dependencies installed");
}

export async function pushSchema() {
  heading("Setting up the database schema");
  // `pnpm --filter <pkg> <script> -- <args>` does NOT forward args the way it looks like it
  // should: pnpm includes the literal `--` in what it hands to the script, and drizzle-kit's own
  // CLI rejects that as an "Unrecognized option" — so `db:push -- --force` fails outright, every
  // time, filter or no filter. `exec` sidesteps the whole problem: it runs the binary directly
  // with the args exactly as given, no script-string concatenation involved.
  await run("pnpm", ["--filter", "@growthos/db", "exec", "drizzle-kit", "push", "--force"], {
    cwd: ROOT,
    env: { ...process.env, DATABASE_URL: LOCAL_DATABASE_URL },
  });
  ok("Database schema is up to date");
}

export async function seedDemoData() {
  heading("Seeding demo data");
  await run("pnpm", ["--filter", "@growthos/api", "exec", "tsx", "scripts/seed-demo.ts"], {
    cwd: ROOT,
    env: { ...process.env, DATABASE_URL: LOCAL_DATABASE_URL, DATABASE_DRIVER: "node-postgres" },
  });
}

async function main() {
  await checkPrereqs();
  writeEnvFiles();
  await installDependencies();
  await startInfra();
  await pushSchema();
  await seedDemoData();
  heading("Setup complete");
  console.log("Run `pnpm local` to start GrowthOS.\n");
}

// Only run when invoked directly (`pnpm setup:local`) — start.mjs imports these functions instead.
if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((err) => {
    fail(err.message ?? String(err));
    process.exit(1);
  });
}
