#!/usr/bin/env node
// `pnpm setup:local` — everything needed before GrowthOS can run locally with zero external
// accounts. Safe to re-run any time: every step here checks what's already true before doing
// anything, so running this twice (or via `pnpm local`, which always runs it first) never
// duplicates work or clobbers a config you've since edited by hand.
//
// What this does NOT do: start the web/API dev servers. That's `pnpm local` (scripts/local/start.mjs),
// which runs everything in this file and then starts them. Use this script directly only if you
// want the infra + demo data ready without the dev servers running yet.

import { existsSync } from "node:fs";
import path from "node:path";
import {
  ok,
  fail,
  info,
  warn,
  heading,
  run,
  runCapture,
  commandExists,
  genHex,
  genBase64,
  ensureEnvFile,
  repoRoot,
} from "./lib.mjs";

export const ROOT = repoRoot();
export const P = (...parts) => path.join(ROOT, ...parts);

// Non-default Postgres port so this can run alongside a system Postgres already on 5432 — see
// docker-compose.local.yml.
export const PORTS = { web: 3000, api: 3001, postgres: 5433, redis: 6379, clickhouse: 8123 };
export const LOCAL_DATABASE_URL = `postgresql://growthos:growthos_local_dev@localhost:${PORTS.postgres}/growthos`;

export const DEMO_EMAIL = "demo@growthos.local";
export const DEMO_PASSWORD = "DemoPass123!";

export async function checkPrereqs() {
  heading("Checking prerequisites");

  const [major] = process.versions.node.split(".").map(Number);
  if (major >= 20) ok(`Node ${process.version}`);
  else {
    fail(`Node ${process.version} — GrowthOS needs Node 20 or newer.`);
    console.log("\n  Install a current Node (e.g. via nvm: https://github.com/nvm-sh/nvm), then re-run this.\n");
    process.exit(1);
  }

  if (!(await commandExists("docker"))) {
    fail("Docker is not installed.");
    console.log("\n  Local Demo Mode needs Docker for Postgres, Redis, and ClickHouse — nothing else to install.");
    console.log("  On Ubuntu / Zorin / Debian:");
    console.log("    sudo apt update && sudo apt install -y docker.io");
    console.log("    sudo usermod -aG docker $USER");
    console.log("  Then log out and back in (group membership needs a fresh session), and re-run this.\n");
    process.exit(1);
  }
  ok("Docker is installed");

  const { code } = await runCapture("docker", ["info"]);
  if (code !== 0) {
    fail("Docker is installed but isn't running (or your user can't reach it).");
    console.log("\n  Start Docker, then re-run this. On Linux, that's usually:");
    console.log("    sudo systemctl start docker");
    console.log("  If you just ran `usermod -aG docker`, log out and back in first.\n");
    process.exit(1);
  }
  ok("Docker is running");
}

